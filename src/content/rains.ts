import { SI_MARK } from "./branches.ts";
import type { Climb, Line, ListenerId, Mark, PersonId, Rain, SpeakerId, Step } from "./types.ts";

// 浴びる: each rain is a branch or a few close ones. Its lines are said by わたし and by the people, to someone and
// sometimes about someone else (`about`), so the learner sees that the ending follows the listener and the raised word
// follows the person in the sentence (CONCEPT.md, 事実 5). Elders speak 반말 down and are raised back. Its climbs
// (上げてみる) say one message to people higher and higher, each answering in their own voice.
// Ids are stable: a line's audio is named for its id's text and voice, and the record keeps rain ids.

/** A word where it shows; `base` when the everyday word above it is not its usual one (커피 드실래요? is 마시다). */
const m = (word: string, text: string, base?: string): Mark => (base ? { word, text, base } : { word, text });
/** The plain -시- of a verb, with the verb it raises. */
const si = (text: string, base: string): Mark => ({ word: SI_MARK, text, base });

function line(id: string, by: SpeakerId, to: ListenerId, ko: string, ja: string, marks: Mark[] = [], about?: string): Line {
  return about ? { id, by, to, about, ko, ja, marks } : { id, by, to, ko, ja, marks };
}

/** One step of a climb: わたし says it to `to`, who answers. */
function step(id: string, to: PersonId, said: [string, string, Mark[]?], reply?: [string, string, Mark[]?], about?: string): Step {
  return {
    said: line(id, "me", to, said[0], said[1], said[2] ?? [], about),
    ...(reply ? { reply: line(`${id}r`, to, "me", reply[0], reply[1], reply[2] ?? []) } : {}),
  };
}

const climb = (id: string, title: string, steps: Step[]): Climb => ({ id, title, steps });

